test('BP-02: poll, post and reply editors show one character counter and keep both schema caps', async ({ page }) => {
  await page.goto('/qa-round1.html?fixture=composer')
  const editor = page.getByTestId('compose-textarea')
  const counter = page.locator('output')
  // No count until the post nears its limit.
  await expect(counter).toHaveCount(0)
  await page.getByRole('button', { name: 'Add poll' }).click()
  await expect(page.getByRole('button', { name: 'Remove poll' })).toBeVisible()
  await editor.fill('a'.repeat(899))
  await expect(counter).toHaveCount(0)
  await editor.fill('a'.repeat(900))
  await expect(counter).toHaveCount(1)
  await expect(counter).toHaveText('100')
  await expect(counter).toHaveAccessibleName('900 of 1000 characters')
  await editor.fill('a'.repeat(1000))
  await expect(counter).toHaveText('0')
  await expect(counter).toHaveAccessibleName('1000 of 1000 characters')
  await editor.press('End')
  await editor.press('a')
  await expect(editor).toHaveValue('a'.repeat(1000))
  await editor.fill('😀'.repeat(500))
  await expect(editor).toHaveValue('😀'.repeat(500))
  await expect(counter).toHaveText('Character limit reached')
  await editor.press('End')
  await editor.press('a')
  await expect(editor).toHaveValue('😀'.repeat(500))
  await page.getByRole('button', { name: 'Toggle preview' }).click()
  await expect(counter).toHaveCount(1)
  await expect(counter).toHaveText('Character limit reached')
  await expect(page.locator('body')).not.toContainText(/bytes/i)
})

