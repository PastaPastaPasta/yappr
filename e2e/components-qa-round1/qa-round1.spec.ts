test('BP-02: private order status notes keep their cap without exposing a byte budget', async ({ page }) => {
  await page.goto('/qa-round1.html?fixture=status')
  const message = page.getByRole('textbox', { name: 'Message to Buyer' })
  await expect(page.locator('body')).not.toContainText(/bytes/i)
  await page.getByRole('textbox', { name: 'Tracking Number' }).fill('TRACK123')
  await message.fill('😀'.repeat(1000))
  const fitted = await message.inputValue()
  expect(fitted.length).toBeGreaterThan(0)
  expect([...fitted].length).toBeLessThan(1000)
  expect([...fitted].every(character => character === '😀')).toBe(true)
  await expect(page.getByRole('status')).toContainText('Character limit reached.')
  await message.press('End')
  await page.keyboard.insertText('😀')
  await expect(message).toHaveValue(fitted)
  await expect(page.getByRole('button', { name: 'Save Status' })).toBeEnabled()
  await expect(page.locator('body')).not.toContainText(/bytes/i)
  await message.fill('Short update')
  await expect(page.getByRole('status')).toHaveCount(0)
})
